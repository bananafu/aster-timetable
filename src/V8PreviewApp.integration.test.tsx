// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { V8PreviewApp } from './V8PreviewApp'
import { APP_DATA_V7_KEY } from './data/storageV7'
import { APP_DATA_V8_KEY } from './data/storageV8'
import { V8_BOOTSTRAP_KEY } from './data/activationV8'

beforeEach(() => {
  localStorage.clear()
  Object.defineProperty(navigator, 'locks', { configurable: true,
    value: { request: (_name: string, _options: unknown, operation: (lock: unknown) => Promise<unknown>) => operation({}) } })
  vi.spyOn(window, 'confirm').mockReturnValue(true)
})
afterEach(() => { cleanup(); localStorage.clear(); vi.restoreAllMocks() })

describe('V8 browser preview shell', () => {
  it('requires explicit bootstrap and then supports a persisted blank Project', async () => {
    const { unmount } = render(<V8PreviewApp onReturn={vi.fn()} />)
    expect(screen.getByText('建立空白 V8 工作空間')).toBeTruthy()
    expect(localStorage.getItem(APP_DATA_V8_KEY)).toBeNull()
    fireEvent.click(screen.getByText('確認建立空白 V8'))
    await waitFor(() => expect(screen.getByText('管理專案')).toBeTruthy())
    expect(JSON.parse(localStorage.getItem(V8_BOOTSTRAP_KEY)!).status).toBe('active')
    fireEvent.click(screen.getByText('管理專案'))
    expect(within(screen.getByRole('dialog', { name: 'V8 專案管理' })).queryByRole('button', { name: '切換專案' })).toBeNull()
    expect(screen.getByText('危險操作')).toBeTruthy()
    fireEvent.click(screen.getByText('新增空白專案'))
    fireEvent.change(screen.getByLabelText('專案名稱'), { target: { value: '新學期' } })
    fireEvent.change(screen.getByLabelText('起始日'), { target: { value: '2027-08-01' } })
    fireEvent.change(screen.getByLabelText('結束日'), { target: { value: '2028-01-31' } })
    await waitFor(() => expect((screen.getByText('新增並切換') as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByText('新增並切換'))
    await waitFor(() => expect(screen.getByText('V8 寫入已確認。')).toBeTruthy())
    const stored = JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!)
    expect(stored.projects).toHaveLength(1)
    expect(stored.subjects).toEqual([])
    expect(stored.classes).toEqual([])
    expect(stored.timetables).toEqual([])
    expect(stored.recurringLessons).toEqual([])
    expect(stored.oneOffLessons).toEqual([])
    expect(stored.overrides).toEqual([])
    expect(stored.events).toEqual([])
    expect(stored.teachingProgress).toEqual([])
    expect(localStorage.getItem(APP_DATA_V7_KEY)).toBeNull()
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    fireEvent.click(screen.getByRole('button', { name: '教師課表' }))
    await waitFor(() => expect((screen.getByRole('button', { name: /新增教師課表/ }) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByText('新增教師課表'))
    fireEvent.change(screen.getByLabelText('課表名稱'), { target: { value: '甲課表' } })
    fireEvent.change(screen.getByLabelText('教師名稱'), { target: { value: '王老師' } })
    fireEvent.click(screen.getByText('建立課表'))
    await waitFor(() => expect(screen.getByText('V8 教師課表已確認儲存。')).toBeTruthy())
    expect(screen.getByText(/目前教師內容：固定課程 0/)).toBeTruthy()
    expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).timetables).toMatchObject([
      { name: '甲課表', teacherName: '王老師' },
    ])
    const originalTimetableId = JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).timetables[0].id
    fireEvent.click(screen.getByText('複製課表設定'))
    fireEvent.change(screen.getByLabelText('來源課表'), { target: { value: originalTimetableId } })
    fireEvent.change(screen.getByLabelText('目的專案'), { target: { value: stored.activeProjectId } })
    fireEvent.click(screen.getByText('複製設定'))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).timetables).toHaveLength(2))
    const copied = JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!)
    expect(copied.timetables[1].id).not.toBe(originalTimetableId)
    expect(copied.recurringLessons).toEqual([])
    expect(copied.oneOffLessons).toEqual([])
    expect(copied.overrides).toEqual([])
    expect(copied.events).toEqual([])
    expect(copied.teachingProgress).toEqual([])
    await waitFor(() => expect((screen.getByText('刪除教師課表') as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByText('刪除教師課表'))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).timetables).toHaveLength(1))
    unmount()
    const reloaded = render(<V8PreviewApp onReturn={vi.fn()} />)
    expect(screen.getAllByText('目前教師課表：甲課表・王老師')).toHaveLength(2)
    fireEvent.click(screen.getByRole('button', { name: '教師課表' }))
    expect((screen.getByLabelText('目前選取的教師課表') as HTMLSelectElement).value).toBe(
      JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).timetables[0].id)
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    fireEvent.click(screen.getByRole('button', { name: '設定' }))
    await waitFor(() => expect((screen.getByText('編輯任教單位') as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByText('編輯任教單位'))
    fireEvent.change(screen.getByLabelText('A/B 錨點日期'), { target: { value: '2027-08-08' } })
    fireEvent.change(screen.getAllByLabelText('開始時間')[0], { target: { value: '08:15' } })
    fireEvent.click(screen.getByText('儲存設定'))
    await waitFor(() => expect(screen.getByText('V8 教學設定已確認儲存。')).toBeTruthy())
    expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).teachingUnits[0].weekCycle.anchorDate).toBe('2027-08-08')
    fireEvent.click(screen.getByText('新增學校'))
    fireEvent.change(screen.getByLabelText('學校名稱'), { target: { value: '第二校' } })
    fireEvent.click(screen.getByText('儲存設定'))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).schools).toHaveLength(2))
    await waitFor(() => expect((screen.getByText('新增任教單位') as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByText('新增任教單位'))
    const secondSchoolId = JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).schools[1].id
    fireEvent.change(screen.getByLabelText('所屬學校'), { target: { value: secondSchoolId } })
    fireEvent.change(screen.getByLabelText('任教單位名稱'), { target: { value: '第二單位' } })
    fireEvent.change(screen.getByLabelText('學期起始日'), { target: { value: '2027-09-01' } })
    fireEvent.change(screen.getByLabelText('學期結束日'), { target: { value: '2028-01-20' } })
    fireEvent.change(screen.getByLabelText('A/B 錨點日期'), { target: { value: '2027-09-08' } })
    fireEvent.change(screen.getByLabelText('錨點週型'), { target: { value: 'B' } })
    fireEvent.click(screen.getByText('儲存設定'))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).teachingUnits).toHaveLength(2))
    expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).teachingUnits[1].weekCycle.anchorPattern).toBe('B')
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    fireEvent.click(screen.getByRole('button', { name: '科目與班級' }))
    fireEvent.click(screen.getByText('進階資料管理：原始匯出與教師科目庫轉換'))
    expect(screen.getByLabelText('教師科目庫版本說明').textContent).toContain('目前教師課表：甲課表')
    expect(screen.getByLabelText('教師科目庫版本說明').textContent).toContain('Project 共用科目庫')
    expect(screen.getAllByRole('button', { name: '匯出原始 V8 JSON' }).length).toBeGreaterThan(0)
    fireEvent.click(screen.getByRole('button', { name: '開啟科目與班級管理' }))
    await waitFor(() => expect((screen.getByText('新增科目') as HTMLButtonElement).disabled).toBe(false))
    fireEvent.change(screen.getByLabelText('新科目名稱'), { target: { value: '數學' } })
    fireEvent.change(screen.getByLabelText('新科目簡稱'), { target: { value: '數' } })
    fireEvent.click(screen.getByText('新增科目'))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).subjects).toHaveLength(1))
    expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).teachingUnitSubjects).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: '班級' }))
    await waitFor(() => expect((screen.getByText('新增班級') as HTMLButtonElement).disabled).toBe(false))
    fireEvent.change(screen.getByLabelText('班級名稱'), { target: { value: '一甲' } })
    fireEvent.click(screen.getByText('新增班級'))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).classes).toHaveLength(1))
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    fireEvent.click(screen.getByRole('button', { name: '教師課表' }))
    await waitFor(() => expect((screen.getByRole('button', { name: /新增教師課表/ }) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByText('新增教師課表'))
    expect((screen.getByLabelText('課表名稱') as HTMLInputElement).value).toBe('')
    expect((screen.getByLabelText('教師名稱') as HTMLInputElement).value).toBe('')
    fireEvent.change(screen.getByLabelText('課表名稱'), { target: { value: '乙課表' } })
    fireEvent.change(screen.getByLabelText('教師名稱'), { target: { value: '李老師' } })
    fireEvent.click(screen.getByText('建立課表'))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).timetables).toHaveLength(2))
    const secondTeacher = JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!)
    expect(secondTeacher.subjects).toHaveLength(1)
    expect(secondTeacher.teachingUnitSubjects).toHaveLength(1)
    expect(secondTeacher.recurringLessons).toEqual([])
    expect(secondTeacher.timetables[1].id).not.toBe(originalTimetableId)
    await waitFor(() => expect((screen.getByLabelText('目前選取的教師課表') as HTMLSelectElement).value)
      .toBe(secondTeacher.timetables[1].id))
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    fireEvent.click(screen.getByRole('button', { name: '科目與班級' }))
    fireEvent.click(screen.getByRole('button', { name: '開啟科目與班級管理' }))
    expect(within(screen.getByLabelText('目前專案科目庫')).getByText('數學')).toBeTruthy()
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    fireEvent.click(screen.getByRole('button', { name: '專案管理' }))
    fireEvent.click(screen.getByText('新增空白專案'))
    fireEvent.change(screen.getByLabelText('專案名稱'), { target: { value: '另一專案' } })
    fireEvent.change(screen.getByLabelText('起始日'), { target: { value: '2028-08-01' } })
    fireEvent.change(screen.getByLabelText('結束日'), { target: { value: '2029-01-31' } })
    fireEvent.click(screen.getByText('新增並切換'))
    await waitFor(() => expect(screen.getByText('V8 寫入已確認。')).toBeTruthy())
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    expect(screen.getAllByText('目前教師課表：尚未建立')).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: '科目與班級' }))
    fireEvent.click(screen.getByRole('button', { name: '開啟科目與班級管理' }))
    expect(screen.getByText('目前專案尚無科目。')).toBeTruthy()
    expect(screen.queryByText('數學')).toBeNull()
    expect(localStorage.getItem(APP_DATA_V7_KEY)).toBeNull()
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    fireEvent.click(screen.getByRole('button', { name: '切換專案' }))
    fireEvent.click(screen.getByRole('menuitemradio', { name: /新學期/ }))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).activeProjectId).toBe(stored.activeProjectId))
    fireEvent.click(screen.getByRole('button', { name: '科目與班級' }))
    fireEvent.click(screen.getByRole('button', { name: '開啟科目與班級管理' }))
    expect(within(screen.getByLabelText('目前專案科目庫')).getByText('數學')).toBeTruthy()
    fireEvent.click(screen.getByLabelText('關閉對話框'))
    const projectBId = JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).projects[1].id
    fireEvent.click(screen.getByRole('button', { name: '切換專案' }))
    fireEvent.click(screen.getByRole('menuitemradio', { name: /另一專案/ }))
    await waitFor(() => expect(JSON.parse(localStorage.getItem(APP_DATA_V8_KEY)!).activeProjectId).toBe(projectBId))
    reloaded.unmount()
    render(<V8PreviewApp onReturn={vi.fn()} />)
    fireEvent.click(screen.getByRole('button', { name: '科目與班級' }))
    fireEvent.click(screen.getByRole('button', { name: '開啟科目與班級管理' }))
    expect(screen.getByText('目前專案尚無科目。')).toBeTruthy()
    expect(screen.queryByText('數學')).toBeNull()
  })

  it('blocks legacy data without touching its exact raw and offers return to V7', () => {
    localStorage.setItem(APP_DATA_V7_KEY, '{legacy-test-raw}')
    const back = vi.fn()
    render(<V8PreviewApp onReturn={back} />)
    expect(screen.getByRole('alert').textContent).toContain('空白 V8 初始化已阻擋')
    expect(screen.queryByText('確認建立空白 V8')).toBeNull()
    expect(localStorage.getItem(APP_DATA_V7_KEY)).toBe('{legacy-test-raw}')
    expect(localStorage.getItem(APP_DATA_V8_KEY)).toBeNull()
    fireEvent.click(screen.getByText('返回 V7'))
    expect(back).toHaveBeenCalledOnce()
  })

  it('fails closed without Web Locks and does not overwrite existing V8', async () => {
    Object.defineProperty(navigator, 'locks', { configurable: true, value: undefined })
    const { unmount } = render(<V8PreviewApp onReturn={vi.fn()} />)
    expect((screen.getByText('確認建立空白 V8') as HTMLButtonElement).disabled).toBe(true)
    expect(screen.getByRole('alert').textContent).toContain('Web Locks')
    unmount()
    localStorage.setItem(APP_DATA_V8_KEY, '{corrupt-v8}')
    render(<V8PreviewApp onReturn={vi.fn()} />)
    expect(screen.getByText('V8 尚無法啟用')).toBeTruthy()
    expect(localStorage.getItem(APP_DATA_V8_KEY)).toBe('{corrupt-v8}')
    expect(screen.getByText('匯出原始 V8 JSON')).toBeTruthy()
    await act(async () => {})
  })

  it('reports lock failure without claiming an active bootstrap', async () => {
    Object.defineProperty(navigator, 'locks', { configurable: true,
      value: { request: async () => { throw new Error('lock failed') } } })
    render(<V8PreviewApp onReturn={vi.fn()} />)
    fireEvent.click(screen.getByText('確認建立空白 V8'))
    await waitFor(() => expect(screen.getByRole('alert').textContent).toContain('lock-failure'))
    expect(localStorage.getItem(APP_DATA_V8_KEY)).toBeNull()
    expect(localStorage.getItem(V8_BOOTSTRAP_KEY)).toBeNull()
  })

  it('keeps valid V8 without active metadata read-only', () => {
    localStorage.setItem(APP_DATA_V8_KEY, JSON.stringify({ schemaVersion: 8, activeProjectId: null,
      projects: [], timetables: [], schools: [], teachingUnits: [], subjects: [], teachingUnitSubjects: [],
      classes: [], recurringLessons: [], events: [], overrides: [], oneOffLessons: [],
      teachingProgress: [], migrationWarnings: [] }))
    render(<V8PreviewApp onReturn={vi.fn()} />)
    expect(screen.getByText('目前無法儲存')).toBeTruthy()
    expect(screen.getByText('管理專案')).toBeTruthy()
    expect(localStorage.getItem(V8_BOOTSTRAP_KEY)).toBeNull()
  })

  it('warns before returning to V7 from a V8-only origin', () => {
    const back = vi.fn()
    vi.mocked(window.confirm).mockReturnValue(false)
    render(<V8PreviewApp onReturn={back} />)
    fireEvent.click(screen.getByText('返回 V7'))
    expect(window.confirm).toHaveBeenCalledWith(expect.stringContaining('V8 為保護資料將停止寫入'))
    expect(back).not.toHaveBeenCalled()
    expect(localStorage.getItem(APP_DATA_V7_KEY)).toBeNull()
  })
})
